async page => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8000');
  await page.setViewportSize({width:1440,height:1000});
  assert(await page.locator('input:visible').count()===1,'One centered input');
  assert(!(await page.locator('#report').isVisible()),'No report before lookup');
  const field=await page.locator('.search-field').boundingBox();
  assert(Math.abs(field.x+field.width/2-720)<2,'VIN field horizontally centered');
  await page.screenshot({path:'/tmp/car-research-centered-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Landing fits mobile');
  await page.screenshot({path:'/tmp/car-research-centered-mobile.png'});
  await page.getByRole('button',{name:'Generate report'}).click();
  assert(await page.locator('#vin').getAttribute('aria-invalid')==='true','Invalid VIN explained inline');
  await page.locator('#vin').fill('1HGCM82633A004352');
  let pending;
  await page.route('**/api/research?*',route=>{pending=route;});
  await page.getByRole('button',{name:'Generate report'}).click();
  await page.locator('#loading').waitFor({state:'visible'});
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert(await page.locator('#vin').isEnabled(),'Cancel restores input');
  await pending?.abort().catch(()=>{});
  await page.unroute('**/api/research?*');
  await page.getByRole('button',{name:'Generate report'}).click();
  await page.locator('#vehicle-title').filter({hasText:'2003 HONDA Accord'}).waitFor({timeout:65000});
  assert(!(await page.locator('#search-view').isVisible()),'Report replaces search screen');
  assert(await page.locator('#decode-source a').count()===1,'Live identity source linked');
  assert(await page.locator('#recalls details').count()>0,'Live recalls retained');
  assert(await page.locator('#fuel-records .fuel-variant').count()>0,'Live EPA configurations displayed');
  assert((await page.locator('#fuel-records').innerText()).includes('MPG'),'EPA units visible');
  assert(await page.locator('#ratings-records .record').count()>0,'Safety variants displayed');
  assert((await page.locator('#carfax-link').getAttribute('href')).endsWith('vin=1HGCM82633A004352'),'CARFAX link contains current VIN');
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.getByRole('button',{name:'Copy VIN',exact:true}).click();
  assert(await page.evaluate(()=>navigator.clipboard.readText())==='1HGCM82633A004352','Copy uses report VIN');
  await page.screenshot({path:'/tmp/car-research-expanded-mobile.png',fullPage:true});
  await page.locator('#safety > .report-disclosure').nth(1).locator('summary').first().click();
  await page.locator('#recalls details').first().locator('summary').click();
  assert(await page.locator('#recalls details').first().getAttribute('open')!==null,'Recall details expand');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Report fits mobile');
  await page.locator('#safety > .report-disclosure').nth(1).locator('summary').first().click();
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'/tmp/car-research-expanded-report.png',fullPage:true});
  await page.getByRole('button',{name:'New lookup'}).click();
  assert(await page.locator('#vin').isVisible(),'New lookup returns to input');
  await page.route('**/api/research?*',route=>route.fulfill({status:502,contentType:'application/json',body:JSON.stringify({error:'Test source unavailable'})}));
  await page.getByRole('button',{name:'Generate report'}).click();
  await page.locator('#lookup-message').filter({hasText:'Test source unavailable'}).waitFor();
  assert(!(await page.locator('#report').isVisible()),'Failure does not show previous report');
  await page.unroute('**/api/research?*');
  await page.getByRole('button',{name:'Generate report'}).click();
  await page.locator('#vehicle-title').filter({hasText:'2003 HONDA Accord'}).waitFor({timeout:65000});
  await page.getByRole('button',{name:'New lookup'}).click();
  assert(errors.length===0,errors.join('\n'));
  return {passed:true,scenarios:['centered entry','mobile entry','validation','cancel','live report transition','expand recall','mobile report','new lookup','error and retry','EPA configs','safety variants','CARFAX VIN link','copy VIN'],pageErrors:errors};
}
